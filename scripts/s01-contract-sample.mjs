import { readFileSync } from 'node:fs';
import { tempFolder, startApi, client } from '../tests/helpers/s01-harness.mjs';
import { runSearchTask } from '../apps/worker/src/search-task.ts';
import { workerDeps } from '../tests/helpers/s02-harness.mjs';
import { runTailor, runRender } from '../tests/helpers/s04-harness.mjs';
import { answers, authorize, pairDevice, prepareForm, readbackFor, runObserve, siteSubmit } from '../tests/helpers/s05-harness.mjs';
import { policyBody, runDiscover } from '../tests/helpers/s06-harness.mjs';
import { runReviewTask } from '../apps/worker/src/review-task.ts';
import { createMockReviewProvider } from '../packages/tailor/src/review-provider.ts';
import { runSupplementTask } from '../apps/worker/src/supplement-task.ts';
import { createMockSupplementProvider } from '../packages/tailor/src/supplement.ts';
import { createMockTailorStageProvider } from '../packages/tailor/src/jd-check.ts';

// 실제 S01·S02·S04·S05·S06 HTTP 응답을 만들어 schema 정의 이름과 함께 출력한다. check_contracts.py가 v0.7 schema로 검증한다.
const { folder, cleanup } = tempFolder('s01-contract-');
const api = await startApi(folder);
const samples = [];
try {
  const loginResponse = await fetch(`${api.base}/api/v1/local-dev/session`, { method: 'POST', headers: { Origin: 'http://127.0.0.1:4310', 'Content-Type': 'application/json' }, body: JSON.stringify({ profile: 'contract' }) });
  const session = await loginResponse.json();
  samples.push(['LocalDevSession', session]);
  const h = client(api, { cookie: loginResponse.headers.getSetCookie().map(value => value.split(';')[0]).join('; '), csrf: session.csrf_token });
  samples.push(['ProductSession', (await h.get('/api/v1/product-session')).body]);
  const pdf = readFileSync(new URL('../fixtures/resumes/frontend.synthetic.pdf', import.meta.url));
  const accepted = await h.upload('/api/v1/resume-documents', pdf, 'frontend.synthetic.pdf');
  samples.push(['TaskAccepted', accepted.body]);
  await api.settle();
  const id = accepted.body.resource_id;
  samples.push(['ResumeDocument', (await h.get(`/api/v1/resume-documents/${id}`)).body]);
  const draft = (await h.get(`/api/v1/resume-documents/${id}/extraction`)).body;
  samples.push(['ExtractionDraft', draft]);
  samples.push(['ResumeSourceText', (await h.get(`/api/v1/resume-documents/${id}/source-text`)).body]);
  samples.push(['Task', (await h.get(`/api/v1/product-tasks/${accepted.body.task.id}`)).body]);
  const confirmed = (await h.post(`/api/v1/resume-documents/${id}/fact-revisions`, { json: { extraction_id: draft.id, expected_parent_revision_id: null, facts: draft.facts } })).body;
  samples.push(['ResumeFactRevision', confirmed]);
  samples.push(['ResumeDocumentList', (await h.get('/api/v1/resume-documents')).body]);
  // v0.7.3: AI 1차 점검(mock) 요청·대기·결과.
  const reviewAccepted = (await h.post(`/api/v1/resume-fact-revisions/${confirmed.id}/ai-reviews`, { json: {} })).body;
  samples.push(['TaskAccepted', reviewAccepted]);
  samples.push(['ResumeAiReview', (await h.get(`/api/v1/resume-ai-reviews/${reviewAccepted.resource_id}`)).body]);
  await runReviewTask({ db: api.db, owner: 'contract-review', leaseMs: 30_000, now: Date.now, provider: createMockReviewProvider() });
  samples.push(['ResumeAiReview', (await h.get(`/api/v1/resume-ai-reviews/${reviewAccepted.resource_id}`)).body]);
  // v0.7.4: 기본 이력서 보완 대화(mock) 시작 → 첫 턴(점검·질문) → 사용자 답변 → 후보·초안 턴. 확정은 하지 않는다(뒤 표본이 같은 확정 버전을 쓴다).
  const supplementDeps = { db: api.db, owner: 'contract-supplement', leaseMs: 30_000, now: Date.now, provider: createMockSupplementProvider() };
  const supplementAccepted = (await h.post(`/api/v1/resume-fact-revisions/${confirmed.id}/supplement-sessions`, { json: {} })).body;
  samples.push(['TaskAccepted', supplementAccepted]);
  samples.push(['ResumeSupplementSession', (await h.get(`/api/v1/resume-supplement-sessions/${supplementAccepted.resource_id}`)).body]);
  await runSupplementTask(supplementDeps);
  samples.push(['TaskAccepted', (await h.post(`/api/v1/resume-supplement-sessions/${supplementAccepted.resource_id}/messages`, { json: { content: '디자인 시스템 문서를 정리했어요. 컴포넌트 수를 40개로 줄였어요.' } })).body]);
  await runSupplementTask(supplementDeps);
  samples.push(['ResumeSupplementSession', (await h.get(`/api/v1/resume-supplement-sessions/${supplementAccepted.resource_id}`)).body]);
  // v0.7.2: 합성 Word(.docx) 원본도 같은 공개 schema로 응답한다.
  const docx = await h.upload('/api/v1/resume-documents', readFileSync(new URL('../fixtures/resumes/frontend.synthetic.docx', import.meta.url)), 'frontend.synthetic.docx');
  await api.settle();
  samples.push(['ResumeDocument', (await h.get(`/api/v1/resume-documents/${docx.body.resource_id}`)).body]);
  samples.push(['ExtractionDraft', (await h.get(`/api/v1/resume-documents/${docx.body.resource_id}/extraction`)).body]);
  samples.push(['ResumeSourceText', (await h.get(`/api/v1/resume-documents/${docx.body.resource_id}/source-text`)).body]);
  // S02: 검색 계획 → 검색 작업(worker 실행) → 검색 결과·공고 스냅샷·작업 상태·중지.
  const conditions = [{ field: 'work_mode', operator: 'any_of', values: ['remote', 'hybrid'], importance: 'required', currency: null }, { field: 'annual_salary', operator: 'gte', values: [60000000], importance: 'preferred', currency: 'KRW' }];
  const intent = (await h.post('/api/v1/search-intents', { json: { fact_revision_id: confirmed.id, conditions } })).body;
  samples.push(['SearchIntent', intent]);
  samples.push(['SearchIntent', (await h.get(`/api/v1/search-intents/${intent.id}`)).body]);
  const search = (await h.post('/api/v1/resume-searches', { json: { intent_id: intent.id, max_candidates: 10 } })).body;
  samples.push(['TaskAccepted', search]);
  samples.push(['SearchRun', (await h.get(`/api/v1/resume-searches/${search.resource_id}`)).body]);
  await runSearchTask(workerDeps(api));
  const run = (await h.get(`/api/v1/resume-searches/${search.resource_id}`)).body;
  samples.push(['SearchRun', run]);
  samples.push(['JobSnapshot', (await h.get(`/api/v1/job-snapshots/${run.job_snapshot_ids[0]}`)).body]);
  samples.push(['Task', (await h.get(`/api/v1/product-tasks/${search.task.id}`)).body]);
  const queued = (await h.post('/api/v1/resume-searches', { json: { intent_id: intent.id, max_candidates: 3 } })).body;
  samples.push(['Task', (await h.post(`/api/v1/product-tasks/${queued.task.id}/cancel`)).body]);
  samples.push(['Problem', (await h.post('/api/v1/search-intents', { json: { fact_revision_id: draft.id, conditions: [] } })).body]);
  // S04: 편집 세션 → 대화(mock) → 제안 수용·부분 수용·거절 → 복원 → 확정 → PDF.
  const tailoring = (await h.post('/api/v1/tailoring-sessions', { json: { job_snapshot_id: run.job_snapshot_ids[0], fact_revision_id: confirmed.id } })).body;
  samples.push(['TailoringSession', tailoring]);
  const r1 = (await h.get(`/api/v1/resume-revisions/${tailoring.current_resume_revision_id}`)).body;
  samples.push(['ResumeRevision', r1]);
  // S1-18 JD 맞춤 점검: 요청(202) → 단계별 진행 기록(progress) → 요구사항 점검표(turn). 답변 턴도 단계별(mock)로 돈다.
  const stages = createMockTailorStageProvider();
  samples.push(['TaskAccepted', (await h.post(`/api/v1/tailoring-sessions/${tailoring.id}/jd-checks`, { json: { expected_resume_revision_id: r1.id } })).body]);
  await runTailor(api, { stages });
  samples.push(['TailoringSession', (await h.get(`/api/v1/tailoring-sessions/${tailoring.id}`)).body]);
  const say = async (content, base) => { const sent = (await h.post(`/api/v1/tailoring-sessions/${tailoring.id}/messages`, { json: { expected_resume_revision_id: base.id, content } })).body; await runTailor(api, { stages }); return sent; };
  samples.push(['TaskAccepted', await say('이 공고에 맞춰 수정해줘', r1)]);
  samples.push(['TailoringMessageList', (await h.get(`/api/v1/tailoring-sessions/${tailoring.id}/messages`)).body]);
  const proposals = (await h.get(`/api/v1/tailoring-sessions/${tailoring.id}/proposals`)).body;
  samples.push(['EditProposalList', proposals]);
  const r2 = (await h.post(`/api/v1/edit-proposals/${proposals.items[0].id}/accept`, { json: { expected_resume_revision_id: r1.id, expected_content_hash: r1.content_hash, change_indexes: [0] } })).body;
  samples.push(['ResumeRevision', r2]);
  await say('Storybook 경험을 강조해줘', r2);
  const open = (await h.get(`/api/v1/tailoring-sessions/${tailoring.id}/proposals`)).body.items.find(item => item.state === 'proposed');
  samples.push(['EditProposal', (await h.post(`/api/v1/edit-proposals/${open.id}/reject`)).body]);
  const restored = (await h.post(`/api/v1/tailoring-sessions/${tailoring.id}/restore`, { json: { source_revision_id: r1.id, expected_resume_revision_id: r2.id } })).body;
  samples.push(['ResumeRevision', restored]);
  samples.push(['ResumeRevisionList', (await h.get(`/api/v1/tailoring-sessions/${tailoring.id}/revisions`)).body]);
  const final = (await h.post(`/api/v1/resume-revisions/${restored.id}/finalize`, { json: { expected_content_hash: restored.content_hash, reviewed: true } })).body;
  samples.push(['ResumeRevision', final]);
  const render = (await h.post('/api/v1/artifacts', { json: { resume_revision_id: final.id } })).body;
  samples.push(['TaskAccepted', render]);
  await runRender(api);
  const artifacts = (await h.get(`/api/v1/resume-revisions/${final.id}/artifacts`)).body;
  samples.push(['RenderedArtifactList', artifacts]);
  samples.push(['RenderedArtifact', (await h.get(`/api/v1/artifacts/${artifacts.items[0].id}`)).body]);
  samples.push(['Task', (await h.get(`/api/v1/product-tasks/${render.task.id}`)).body]);
  samples.push(['TailoringSession', (await h.get(`/api/v1/tailoring-sessions/${tailoring.id}`)).body]);
  samples.push(['TaskList', (await h.get(`/api/v1/tailoring-sessions/${tailoring.id}/tasks`)).body]);
  // S05: 지원 건 → 실행기 연결·폼 관측(확장 역할) → 수동 권한 → 시도 → 전송 → 접수 확인 → 이력·채용 단계·외부 기록.
  const app = (await h.post('/api/v1/job-applications', { json: { job_snapshot_id: final.job_snapshot_id, resume_revision_id: final.id, artifact_id: artifacts.items[0].id, answers: [] } })).body;
  samples.push(['Application', app]);
  const answered = (await h.patch(`/api/v1/job-applications/${app.id}`, { json: { expected_revision: 1, job_snapshot_id: final.job_snapshot_id, resume_revision_id: final.id, artifact_id: artifacts.items[0].id, answers: answers() } })).body;
  samples.push(['Application', answered]);
  samples.push(['ExecutorPairing', (await h.post('/api/v1/executor-pairings', { json: { executor: 'chrome' } })).body]);
  const device = await pairDevice(api, h);
  samples.push(['ExecutorDeviceList', (await h.get('/api/v1/executor-devices')).body]);
  const form = await prepareForm(device, app.id);
  const grant = (await authorize(h, answered, form.verified.body)).body;
  samples.push(['ApplicationAuthorization', grant]);
  const attempt = (await h.post(`/api/v1/job-applications/${app.id}/attempts`, { json: { authorization_id: grant.id } })).body;
  samples.push(['SubmissionAttempt', attempt]);
  const claim = (await device.post(`/attempts/${attempt.id}/claim`)).body;
  await device.post(`/attempts/${attempt.id}/dispatch`, { run_token: claim.run_token, target_url: claim.target_url, document_id: 'contract-doc', snapshot: form.snapshot, readback: readbackFor(claim.fill, form.file.body) });
  // 실행기가 결과를 보지 못하고 끊긴 뒤(접수 불명) 늦게 도착한 전송이 사이트에 저장된 경우 → 접수 결과 확인으로 확정.
  samples.push(['SubmissionAttempt', (await device.post(`/attempts/${attempt.id}/result`, { run_token: claim.run_token, outcome: 'no_confirmation', detail: 'contract-sample', observed: null })).body]);
  await siteSubmit(api, form.plan.body.posting_id, claim.fill, form.file.body, attempt.id);
  samples.push(['TaskAccepted', (await h.post(`/api/v1/submission-attempts/${attempt.id}/observe`, { json: {} })).body]);
  runObserve(api);
  const settled = (await h.get(`/api/v1/submission-attempts/${attempt.id}`)).body;
  samples.push(['SubmissionAttempt', settled]);
  samples.push(['SubmissionEvidence', (await h.get(`/api/v1/submission-evidence/${settled.evidence_ids[0]}`)).body]);
  samples.push(['Application', (await h.post(`/api/v1/job-applications/${app.id}/recruitment-events`, { json: { expected_application_revision: 2, stage: 'review', note: '서류 검토 안내' } })).body]);
  const other = run.job_snapshot_ids.find(jobId => jobId !== final.job_snapshot_id);
  const otherJob = (await h.get(`/api/v1/job-snapshots/${other}`)).body;
  samples.push(['ExternalApplication', (await h.post('/api/v1/external-applications', { json: { job_snapshot_id: other, company_name: otherJob.company_name, title: otherJob.title, channel: '회사 채용 홈페이지', applied_on: '2026-11-01', note: '' } })).body]);
  samples.push(['ExternalApplicationList', (await h.get('/api/v1/external-applications')).body]);
  samples.push(['ApplicationList', (await h.get('/api/v1/job-applications')).body]);
  samples.push(['ApplicationHistory', (await h.get(`/api/v1/job-applications/${app.id}/history`)).body]);
  samples.push(['Problem', (await h.post(`/api/v1/submission-attempts/${attempt.id}/observe`, { json: {} })).body]);
  // S06: 정책 작성·활성화 → 캠페인 → 탐색·자동 준비(worker) → 대기함. 기기 해제 전에 binding으로 정책을 만든다.
  const policyRequest = policyBody({ prepared: { revision: final }, bindingId: form.verified.body.target.account_binding_id }, { mode: 'prepare' });
  const policy = (await h.post('/api/v1/auto-apply-policies', { json: policyRequest })).body;
  samples.push(['AutoApplyPolicyRevision', policy]);
  samples.push(['PolicyControl', (await h.get(`/api/v1/auto-apply-policies/${policy.policy_id}`)).body]);
  samples.push(['PolicyControl', (await h.post(`/api/v1/auto-apply-policies/${policy.policy_id}/activate`, { json: { revision_id: policy.id, expected_generation: 1, accepted_content_hash: policy.content_hash, consent: true } })).body]);
  samples.push(['AutoApplyPolicyRevisionList', (await h.get('/api/v1/auto-apply-policies')).body]);
  samples.push(['AutoApplyPolicyRevision', (await h.get(`/api/v1/auto-apply-policies/${policy.policy_id}/revisions/${policy.id}`)).body]);
  const campaign = (await h.post('/api/v1/similar-job-campaigns', { json: { policy_revision_id: policy.id, seed_application_id: app.id } })).body;
  samples.push(['SimilarJobCampaign', campaign]);
  samples.push(['TaskAccepted', (await h.post(`/api/v1/similar-job-campaigns/${campaign.id}/run`, { json: {} })).body]);
  await runDiscover(api);
  samples.push(['CampaignQueue', (await h.get(`/api/v1/similar-job-campaigns/${campaign.id}/queue`)).body]);
  samples.push(['SimilarJobCampaignList', (await h.get('/api/v1/similar-job-campaigns')).body]);
  samples.push(['SimilarJobCampaign', (await h.post(`/api/v1/similar-job-campaigns/${campaign.id}/pause`, { json: {} })).body]);
  samples.push(['PolicyControl', (await h.post(`/api/v1/auto-apply-policies/${policy.policy_id}/pause`, { json: { expected_generation: 2 } })).body]);
  samples.push(['Problem', (await h.post('/api/v1/auto-apply-policies', { json: { ...policyRequest, mode: 'submit' } })).body]);
  samples.push(['ExecutorDevice', (await h.post(`/api/v1/executor-devices/${device.info.device_id}/revoke`, { json: {} })).body]);
  samples.push(['Problem', (await h.post('/api/v1/artifacts', { json: { resume_revision_id: r2.id } })).body]);
  const pasted = await h.post('/api/v1/resume-documents/text', { json: { text: '' } });
  samples.push(['Problem', pasted.body]);
  const blank = await h.upload('/api/v1/resume-documents', Buffer.from('%PDF-1.4\n%%EOF\n'), 'blank.pdf');
  await api.settle();
  samples.push(['ExtractionDraft', (await h.get(`/api/v1/resume-documents/${blank.body.resource_id}/extraction`)).body]);
  samples.push(['Problem', (await client(api, null).get('/api/v1/resume-documents')).body]);
  console.log(JSON.stringify(samples));
} finally {
  await api.stop();
  cleanup();
}
